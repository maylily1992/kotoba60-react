function compose(template: string, item: BankItem) {
  return template.replaceAll("{x}", item.jp).replaceAll("{k}", item.kana).replaceAll("{z}", item.zh);
}

export const DAYS: BankDay[] = DAY_CONFIGS.map((config) => {
  const pool = ITEM_POOLS[config.set];
  const offset = (config.day * 3) % pool.length;
  const items = Array.from({ length: 10 }, (_, index) => pool[(offset + index) % pool.length]);
  const frames = FRAME_SETS[config.set];
  const cards = frames.flatMap((frame) =>
    items.map((item, itemIndex) => ({
      id: `${config.day}-${frame.grammar}-${itemIndex}`,
      day: config.day,
      jp: compose(frame.jp, item),
      kana: compose(frame.kana, item),
      zh: compose(frame.zh, item),
      grammar: frame.grammar,
      why: frame.why,
      item,
      related: frames.filter((other) => other !== frame && other.grammar !== frame.grammar).slice(0, 2).map((other) => compose(other.jp, item)),
    })),
  );
  const counts = cards.reduce<Record<string, number>>((map, card) => {
    map[card.grammar] = (map[card.grammar] ?? 0) + 1;
    return map;
  }, {});
  return {
    ...config,
    items,
    frames,
    cards,
    grammarSummary: Object.entries(counts).map(([label, examples]) => ({ label, examples })),
    relatedTags: frames.slice(0, 5).map((frame) => frame.grammar),
  };
});

export const TOTAL_SENTENCES = DAYS.reduce((sum, day) => sum + day.cards.length, 0);
